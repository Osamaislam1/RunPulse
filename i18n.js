let currentLang = 'en';

function t(key, vars) {
    const pack = I18N[currentLang] || I18N.en;
    let s = pack[key] || I18N.en[key] || key;
    if (vars) {
        Object.keys(vars).forEach(k => {
            s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
        });
    }
    return s;
}

function setLanguage(lang) {
    currentLang = I18N[lang] ? lang : 'en';
    try { localStorage.setItem(LANG_KEY, currentLang); } catch (e) { }
    document.documentElement.lang = currentLang;
    applyI18n();
}

function applyI18n() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!key) return;
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = t(key);
        } else {
            el.textContent = t(key);
        }
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.getAttribute('data-i18n-title'));
    });
    // Refresh dynamic buttons that rebuild innerHTML
    const btnStart = document.getElementById('btnStart');
    if (btnStart && !btnStart.classList.contains('running') && !isPaused) {
        if (!isRunning) {
            btnStart.innerHTML = `<i class="fa-solid fa-play"></i> ${t('startRun')}`;
        }
    }
    const voiceBtn = document.getElementById('voiceToggle');
    if (voiceBtn) {
        const on = voiceBtn.classList.contains('active');
        voiceBtn.setAttribute('aria-label', on ? t('voiceOn') : t('voiceOff'));
        voiceBtn.title = on ? t('voiceOn') : t('voiceOff');
    }
}

function initI18n() {
    try {
        const saved = localStorage.getItem(LANG_KEY);
        if (saved && I18N[saved]) currentLang = saved;
    } catch (e) { }
    document.documentElement.lang = currentLang;
    const sel = document.getElementById('langSelect');
    if (sel) sel.value = currentLang;
    applyI18n();
}
